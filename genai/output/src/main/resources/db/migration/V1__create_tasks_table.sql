CREATE TABLE tasks (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_username VARCHAR(255) NOT NULL,
    title          VARCHAR(200) NOT NULL,
    description    VARCHAR(2000),
    status         VARCHAR(20)  NOT NULL DEFAULT 'TODO',
    due_date       DATE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT fk_tasks_owner FOREIGN KEY (owner_username) REFERENCES users (username) ON DELETE CASCADE,
    CONSTRAINT ck_tasks_title_not_blank CHECK (char_length(btrim(title)) > 0),
    CONSTRAINT ck_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE'))
);

CREATE INDEX idx_tasks_owner_due_date ON tasks (owner_username, due_date, id);
CREATE INDEX idx_tasks_owner_status ON tasks (owner_username, status);
